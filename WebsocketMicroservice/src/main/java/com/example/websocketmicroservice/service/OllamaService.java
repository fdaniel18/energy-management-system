package com.example.websocketmicroservice.service;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.stereotype.Service;
import org.springframework.web.client.RestTemplate;

import java.util.HashMap;
import java.util.Map;

@Service
@RequiredArgsConstructor
@Slf4j
public class OllamaService {

    private final RestTemplate restTemplate = new RestTemplate();
    private final ObjectMapper objectMapper;

    @Value("${ollama.api.url:http://host.docker.internal:11434/api/generate}")
    private String ollamaApiUrl;

    @Value("${ollama.model:qwen3:8b}")
    private String ollamaModel;

    private static final String SYSTEM_PROMPT = """
            You are a helpful customer support assistant for an Energy Management System (EMS).
            The system allows users to:
            - Monitor energy consumption of their devices.
            - Manage devices (add, update, delete).
            - Receive notifications for overconsumption.
            - View historical consumption data.
            
            Answer the user's question concisely and professionally based on this context.
            If the question is unrelated to energy management or devices, politely decline to answer.
            Do not make up features that are not listed above.
            """;

    public String getAnswer(String userQuestion) {
        try {
            Map<String, Object> requestBody = new HashMap<>();
            requestBody.put("model", ollamaModel.trim());
            requestBody.put("prompt", SYSTEM_PROMPT + "\n\nUser Question: " + userQuestion + "\nAnswer:");
            requestBody.put("stream", false);

            Map<String, Object> response = restTemplate.postForObject(ollamaApiUrl, requestBody, Map.class);

            if (response != null && response.containsKey("response")) {
                String rawResponse = (String) response.get("response");
                // Remove <think>...</think> blocks generated by some models
                return rawResponse.replaceAll("<think>[\\s\\S]*?</think>", "").trim();
            }
        } catch (Exception e) {
            log.error("Error calling Ollama API: {}", e.getMessage());
        }
        return "I'm currently unable to reach the AI support assistant. Please contact admin.";
    }
}
